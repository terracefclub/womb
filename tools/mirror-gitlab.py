#!/usr/bin/env python3
"""Mirror only published GitHub refs, without force or deletion, to GitLab."""
import json
import os
import pathlib
import re
import subprocess
import tempfile

# Published by GitLab over HTTPS; never learned through unauthenticated keyscan.
# https://docs.gitlab.com/user/gitlab_com/#ssh-host-keys-fingerprints
HOST_KEY = "gitlab.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIAfuCHKVTjquxvt6CM6tdG4SLp1Btn/nOeHHE5UOzRdf\n"
CONFIGS = {
    "terracefclub/womb": ("terrace/tech/womb", ("trunk",), ""),
    "terracefclub/tfc-website": ("terrace/tech/tfc-website", ("dev", "prod", "dev-post-vanilla"), "github/"),
}


class MirrorFailure(RuntimeError):
    def __init__(self, stage, code=None, stderr=b"", timeout=False):
        facts = {"stage": stage, "returncode": code, "timeout": timeout,
                 "sshPermissionDenied": b"Permission denied (publickey)" in stderr,
                 "hostVerificationFailed": b"Host key verification failed" in stderr,
                 "connectionRefused": b"Connection refused" in stderr,
                 "connectionTimedOut": b"Connection timed out" in stderr,
                 "remoteRefused": b"remote rejected" in stderr,
                 "stderrTruncated": len(stderr) > 65536}
        super().__init__(json.dumps(facts, sort_keys=True))


def refspecs(repo, heads, tags):
    if repo not in CONFIGS:
        raise ValueError("Unsupported repository")
    _, allowed, prefix = CONFIGS[repo]
    if set(heads) != set(allowed):
        raise ValueError("Published branch inventory is incomplete")
    if any(not re.fullmatch(r"[0-9a-f]{40}", value) for value in heads.values()):
        raise ValueError("Invalid commit identity")
    result = [f"{heads[name]}:refs/heads/{prefix}{name}" for name in allowed]
    for tag in tags:
        if not tag.startswith("refs/tags/") or tag.endswith("/") or any(x in tag for x in ("..", "@{", "\\", " ", ":", "~", "^", "?", "*", "[")):
            raise ValueError("Invalid published tag")
        result.append(f"{tag}:refs/tags/{prefix}{tag[len('refs/tags/'):]}")
    return result


def main():
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    if repo not in CONFIGS:
        raise ValueError("Unsupported repository")
    key = os.environ.pop("GITLAB_MIRROR_KEY", "")
    if not key.startswith("-----BEGIN OPENSSH PRIVATE KEY-----\n"):
        raise MirrorFailure("credential-format")
    destination, branches, _ = CONFIGS[repo]
    env = dict(os.environ)
    env.pop("GITHUB_TOKEN", None)
    with tempfile.TemporaryDirectory(prefix="terrace-mirror-") as temporary:
        root = pathlib.Path(temporary)
        identity = root / "identity"
        identity.write_text(key)
        identity.chmod(0o600)
        key = None
        known = root / "known_hosts"
        known.write_text(HOST_KEY)
        known.chmod(0o600)
        # These paths are generated by tempfile, not supplied by a ref or a user.
        env["GIT_SSH_COMMAND"] = (f"ssh -F /dev/null -i {identity} -o IdentitiesOnly=yes "
                                  f"-o UserKnownHostsFile={known} -o StrictHostKeyChecking=yes "
                                  "-o BatchMode=yes -o ConnectTimeout=15 -o HostKeyAlgorithms=ssh-ed25519")
        def git(*args):
            # Only fixed command names are allowed in public failure witnesses.
            stage = args[0]
            if stage not in {"init", "fetch", "rev-parse", "for-each-ref", "push", "ls-remote"}:
                raise MirrorFailure("invalid-stage")
            with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as error:
                try:
                    result = subprocess.run(["git", "-C", str(root), *args], env=env,
                                            stdout=output, stderr=error, timeout=120)
                except subprocess.TimeoutExpired:
                    error.seek(0)
                    raise MirrorFailure(stage, stderr=error.read(65537), timeout=True) from None
                error.seek(0)
                diagnostic = error.read(65537)
                if result.returncode:
                    raise MirrorFailure(stage, result.returncode, diagnostic)
                output.seek(0)
                data = output.read(1048577)
                if len(data) > 1048576:
                    raise MirrorFailure("output-limit")
                return data.decode("utf-8", errors="strict")
        git("init", "--bare", "--quiet")
        git("fetch", "--quiet", f"https://github.com/{repo}.git",
            *[f"refs/heads/{name}:refs/heads/{name}" for name in branches], "refs/tags/*:refs/tags/*")
        heads = {name: git("rev-parse", f"refs/heads/{name}").strip() for name in branches}
        tags = git("for-each-ref", "--format=%(refname)", "refs/tags").splitlines()
        specs = refspecs(repo, heads, tags)
        git("push", "--atomic", "--push-option=ci.skip", f"git@gitlab.com:{destination}.git", *specs)
        actual = dict(line.split()[::-1] for line in git("ls-remote", f"git@gitlab.com:{destination}.git").splitlines())
        for spec in specs:
            source, target = spec.split(":", 1)
            expected = source if re.fullmatch(r"[0-9a-f]{40}", source) else git("rev-parse", source).strip()
            if actual.get(target) != expected:
                raise ValueError("Mirror verification failed")
        print(json.dumps({"mirroredBranches": len(heads), "mirroredTags": len(tags), "verified": True}))


if __name__ == "__main__":
    try:
        main()
    except MirrorFailure as error:
        raise SystemExit(str(error)) from None
    except Exception:
        raise SystemExit("Mirror failed; no force or deletion was attempted") from None
